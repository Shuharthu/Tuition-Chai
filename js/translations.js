class TranslationManager {
  constructor() {
    this.currentLang = localStorage.getItem('tc_language') || 'en';
    this.init();
  }

  init() {
    this.applyLanguage(this.currentLang);
  }

  setLanguage(lang) {
    if (lang !== 'en' && lang !== 'bn') return;
    this.currentLang = lang;
    localStorage.setItem('tc_language', lang);
    this.applyLanguage(lang);
  }

  get(key) {
    return translations[this.currentLang][key] || translations['en'][key] || key;
  }

  applyLanguage(lang) {
    document.documentElement.lang = lang;
    if (lang === 'bn') {
      document.body.classList.add('lang-bn');
    } else {
      document.body.classList.remove('lang-bn');
    }

    // Update switcher UI buttons if present
    const enBtns = document.querySelectorAll('.lang-btn-en');
    const bnBtns = document.querySelectorAll('.lang-btn-bn');
    enBtns.forEach(btn => btn.classList.toggle('active', lang === 'en'));
    bnBtns.forEach(btn => btn.classList.toggle('active', lang === 'bn'));

    // Translate all elements with data-i18n
    const translatableElements = document.querySelectorAll('[data-i18n]');
    translatableElements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (translations[lang] && translations[lang][key]) {
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          if (el.hasAttribute('placeholder')) {
            el.setAttribute('placeholder', translations[lang][key]);
          }
        } else {
          el.textContent = translations[lang][key];
        }
      }
    });
  }
}

// Global instance
window.i18n = new TranslationManager();
